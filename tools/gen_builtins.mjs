// Regenerates the built-in content from the browser prototype, so the native
// tables match it exactly:
//   source/core/builtin_spells.c    45 starter spells (STARTER)
//   source/core/builtin_features.c  11 starter features (FSTARTER)
//   source/core/demo_files.c        library templates + Jedediah's homebrew + his portrait BMP
//   source/gfx/icons_data.c         the 21 pixel icons (ICONS)
//   sd-card/data/pocketsheet/portrait1.bmp
// It also checks that assets/font5x7.h still matches the prototype's FONT.
//
// Usage (from the repo root): node tools/gen_builtins.mjs
import { readFileSync, writeFileSync, mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const simPath = join(root, 'docs/handoff/prototype/pocket-sheet-sim-v2.js');

// The prototype keeps these as module-private consts; re-export them from a temporary copy.
const names = ['STARTER', 'FSTARTER', 'DEMO_PORTRAIT1', 'SPELLS_TEMPLATE', 'DEMO_SPELLS', 'FEATURES_TEMPLATE', 'DEMO_FEATURES', 'cleanText', 'FCAT'];
// FONT and ICONS are already exported by the prototype.
const tmp = mkdtempSync(join(tmpdir(), 'pocketsheet-gen-'));
const tmpFile = join(tmp, 'sim.mjs');
writeFileSync(tmpFile, readFileSync(simPath, 'utf8') + `\nexport { ${names.join(', ')} };\n`);
const sim = await import(pathToFileURL(tmpFile).href);
rmSync(tmp, { recursive: true, force: true });

// C string literal: JSON escapes are valid C for ASCII text; break "??" so it can't form a trigraph.
const lit = s => {
  if (/[^\x20-\x7e\n]/.test(s)) throw new Error('non-ASCII text: ' + s.slice(0, 40));
  return JSON.stringify(s).replace(/\?\?/g, '?\\?');
};
const header = src => `// GENERATED by tools/gen_builtins.mjs from ${src}. Do not edit by hand.\n`;

// ---- spells ----
const spells = sim.STARTER.map(([name, level, school, time, range, comp, dur, tags, desc]) =>
  `    { ${lit(name)}, ${level}, ${lit(school)}, ${lit(time)}, ${lit(range)}, ${lit(comp)}, ${lit(dur)}, ${tags.includes('C') ? 1 : 0}, ${tags.includes('R') ? 1 : 0},\n      ${lit(sim.cleanText(desc))} },`);
writeFileSync(join(root, 'source/core/builtin_spells.c'), header('the prototype STARTER table') +
`// Descriptions are original short paraphrases (2024-style numbers).
#include "spells.h"

const SpellDef SPELL_BUILTINS[] = {
${spells.join('\n')}
};
const int SPELL_BUILTIN_COUNT = (int)(sizeof SPELL_BUILTINS / sizeof SPELL_BUILTINS[0]);
`);

// ---- features ----
const usesC = u => !u ? 'USES_NONE, 0' : u === 'PB' ? 'USES_PB, 0' : ['STR', 'DEX', 'CON', 'INT', 'WIS', 'CHA'].includes(u) ? `USES_ABILITY, AB_${u}` : `USES_FIXED, ${Math.min(20, +u)}`;
const resetC = (r, u) => ({ LONG: 'RESET_LONG', SHORT: 'RESET_SHORT', SHORT1: 'RESET_SHORT1', NONE: 'RESET_MANUAL', '': 'RESET_UNSET' })[r || (u ? 'LONG' : '')];
const feats = sim.FSTARTER.map(([name, cat, uses, reset, tags, desc]) =>
  `    { ${lit(name)}, ${Math.max(0, sim.FCAT.indexOf(cat))}, ${usesC(uses)}, ${resetC(reset, uses)}, ${/INSPIRE/.test(tags) ? 1 : 0},\n      ${lit(sim.cleanText(desc))} },`);
writeFileSync(join(root, 'source/core/builtin_features.c'), header('the prototype FSTARTER table') +
`#include "features.h"

const FeatureDef FEATURE_BUILTINS[] = {
${feats.join('\n')}
};
const int FEATURE_BUILTIN_COUNT = (int)(sizeof FEATURE_BUILTINS / sizeof FEATURE_BUILTINS[0]);
`);

// ---- demo files ----
const bmp = Buffer.from(sim.DEMO_PORTRAIT1, 'base64');
writeFileSync(join(root, 'sd-card/data/pocketsheet/portrait1.bmp'), bmp);
const bytes = [];
for (let i = 0; i < bmp.length; i += 16) bytes.push('    ' + [...bmp.subarray(i, i + 16)].map(b => b + ',').join(' '));
// Long texts are split at line boundaries into adjacent literals to stay under C's 4095-char literal limit.
const longLit = s => s.split(/(?<=\n)/).map(l => '    ' + lit(l)).join('\n');
writeFileSync(join(root, 'source/core/demo_files.c'), header('the prototype') +
`// Library file templates written on first run, Jedediah Graves's homebrew entries,
// and his portrait (user-supplied art, not CC0) as a 48x48 24-bit BMP.
#include "demo.h"

const char DEMO_SPELLS_TEMPLATE[] =
${longLit(sim.SPELLS_TEMPLATE)};

const char DEMO_SPELLS_JED[] =
${longLit(sim.DEMO_SPELLS)};

const char DEMO_FEATURES_TEMPLATE[] =
${longLit(sim.FEATURES_TEMPLATE)};

const char DEMO_FEATURES_JED[] =
${longLit(sim.DEMO_FEATURES)};

const unsigned char DEMO_PORTRAIT1_BMP[${bmp.length}] = {
${bytes.join('\n')}
};
`);
// ---- icons ----
// assets/icons.h predates the gold book icon (mbook) on the FEATS tab, so the
// table is generated from the prototype's ICONS, in the order of the IC_* enum.
const ICON_ORDER = ['sword', 'arrow', 'heart', 'shield', 'skull', 'fire', 'fire2', 'moon', 'star', 'bolt', 'boot', 'eye',
  'mpage', 'mheart', 'msword', 'mspark', 'mbook', 'mquill', 'mskull', 'mstar', 'mshield'];
const missing = Object.keys(sim.ICONS).filter(n => !ICON_ORDER.includes(n));
if (missing.length) throw new Error('icons not in IC_* order: ' + missing.join(', '));
const icons = ICON_ORDER.map(n => {
  const rows = sim.ICONS[n];
  return `    { ${rows[0].length}, ${rows.length}, { ${rows.map(r => lit(r)).join(', ')} } }, // ${n}`;
});
writeFileSync(join(root, 'source/gfx/icons_data.c'), header('the prototype ICONS table') +
`// Original pixel art, CC0. Rows: '.' clear, '#' color 0, '+' color 1, '=' color 2.
#include "icons_data.h"

const IconDef ICON_DEFS[IC_COUNT] = {
${icons.join('\n')}
};
`);

// ---- font check ----
// assets/font5x7.h is compiled in as-is; make sure it still matches the prototype's FONT.
const fontH = readFileSync(join(root, 'assets/font5x7.h'), 'utf8');
const rowsH = [...fontH.matchAll(/\{((?:\s*0x[0-9a-f]{2},?){7})\s*\}/gi)].map(m => m[1].split(',').map(v => parseInt(v, 16)).filter(v => !isNaN(v)));
const CUSTOM = ['♥', '✓', '✗', '▶', '◀', '▲', '▼', '●', '○', '◆', '→'];
let fontErrors = 0;
for (const [ch, rows] of Object.entries(sim.FONT)) {
  const idx = CUSTOM.includes(ch) ? 96 + CUSTOM.indexOf(ch) : ch.charCodeAt(0) - 32;
  const want = rows.split(' ').map(r => [...r].reduce((v, p) => (v << 1) | (p === '#' ? 1 : 0), 0));
  if (JSON.stringify(rowsH[idx]) !== JSON.stringify(want)) { fontErrors++; console.error('font mismatch for', ch); }
}
if (fontErrors) throw new Error(fontErrors + ' font glyphs differ from the prototype');
console.log(`spells ${sim.STARTER.length}, features ${sim.FSTARTER.length}, portrait ${bmp.length} bytes, icons ${icons.length}, font ok`);
